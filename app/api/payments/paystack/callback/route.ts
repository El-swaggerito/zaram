import { env } from "cloudflare:workers";

import { confirmBookingPayment } from "@/lib/payments/confirm-booking-payment";
import { verifyPaystackTransaction } from "@/lib/payments/paystack";

export const dynamic = "force-dynamic";

type PaymentAttemptRow = {
  id: number;
  booking_id: number;
  reference: string;
  amount_kobo: number;
  currency: string;
  booking_reference: string;
};

function redirectTo(
  request: Request,
  path: string
) {
  return Response.redirect(
    new URL(path, request.url),
    303
  );
}

export async function GET(request: Request) {
  const url = new URL(request.url);

  const reference =
    url.searchParams.get("reference")?.trim();

  if (!reference) {
    return redirectTo(
      request,
      "/rooms?payment=missing-reference"
    );
  }

  const db = env.zaram_hotels_db;

  /*
   * Only references generated by our own server are accepted.
   */
  const attempt = await db
    .prepare(
      `
        SELECT
          pt.id,
          pt.booking_id,
          pt.reference,
          pt.amount_kobo,
          pt.currency,
          b.booking_reference
        FROM payment_transactions pt
        JOIN bookings b
          ON b.id = pt.booking_id
        WHERE
          pt.reference = ?
          AND pt.provider = 'paystack'
        LIMIT 1
      `
    )
    .bind(reference)
    .first<PaymentAttemptRow>();

  if (!attempt) {
    return redirectTo(
      request,
      "/rooms?payment=unknown-reference"
    );
  }

  let transaction;

  try {
    transaction =
      await verifyPaystackTransaction(reference);
  } catch (error) {
    console.error(
      "Paystack callback verification failed:",
      error
    );

    return redirectTo(
      request,
      `/payment/${encodeURIComponent(
        attempt.booking_reference
      )}?payment=verification-error`
    );
  }

  /*
   * Update our record with the latest Paystack status even when
   * payment has not succeeded.
   */
  if (transaction.status !== "success") {
    const allowedStatuses = new Set([
      "abandoned",
      "failed",
      "ongoing",
      "pending",
      "processing",
      "queued",
      "reversed",
    ]);

    const status = allowedStatuses.has(
      transaction.status
    )
      ? transaction.status
      : "failed";

    await db
      .prepare(
        `
          UPDATE payment_transactions
          SET
            status = ?,
            gateway_response = ?,
            verified_at = CURRENT_TIMESTAMP,
            updated_at = CURRENT_TIMESTAMP
          WHERE id = ?
        `
      )
      .bind(
        status,
        transaction.gateway_response,
        attempt.id
      )
      .run();

    return redirectTo(
      request,
      `/payment/${encodeURIComponent(
        attempt.booking_reference
      )}?payment=${encodeURIComponent(status)}`
    );
  }

  /*
   * Never trust a successful status by itself.
   * Reference, exact amount and NGN currency must all match
   * the values recorded before the guest left our site.
   */
  if (
    transaction.reference !== attempt.reference ||
    transaction.amount !== attempt.amount_kobo ||
    transaction.currency !== attempt.currency ||
    transaction.currency !== "NGN"
  ) {
    console.error(
      "Paystack verification mismatch:",
      {
        reference: transaction.reference,
        expectedReference: attempt.reference,
        amount: transaction.amount,
        expectedAmount: attempt.amount_kobo,
        currency: transaction.currency,
        expectedCurrency: attempt.currency,
      }
    );

    return redirectTo(
      request,
      `/payment/${encodeURIComponent(
        attempt.booking_reference
      )}?payment=verification-mismatch`
    );
  }

  const result = await confirmBookingPayment({
    bookingReference:
      attempt.booking_reference,
    paymentReference:
      attempt.reference,
    paymentProvider: "paystack",
    amountPaidKobo:
      transaction.amount,
    paidAt:
      transaction.paid_at,
    /*
     * Paystack recommends treating transaction IDs as unsigned
     * 64-bit values. We store it as TEXT in D1.
     */
    providerTransactionId:
      String(transaction.id),
    gatewayResponse:
      transaction.gateway_response,
  });

  if (!result.success) {
    console.error(
      "Verified Paystack payment could not confirm booking:",
      result
    );

    return redirectTo(
      request,
      `/payment/${encodeURIComponent(
        attempt.booking_reference
      )}?payment=manual-review`
    );
  }

  return redirectTo(
    request,
    `/booking/confirmed/${encodeURIComponent(
      attempt.booking_reference
    )}`
  );
}
